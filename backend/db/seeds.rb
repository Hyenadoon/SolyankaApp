RECIPES.each do |data|
  recipe = Recipe.find_or_create_by!(name: data[:name]) do |r|
    r.description = data[:description]
    r.cooking_time_minutes = data[:cooking_time_minutes]
    r.servings = data[:servings]
    r.steps_count = data[:steps].size
  end

  next if recipe.recipe_ingredients.any?

  data[:ingredients].each do |ing_data|
    ing = ingredient_map[ing_data[:n]]
    unless ing
      puts "  WARNING: Ingredient '#{ing_data[:n]}' not found, skipping"
      next
    end
    recipe.recipe_ingredients.create!(
      ingredient: ing,
      amount: ing_data[:a],
      unit: ing_data[:u]
    )
  end

  data[:steps].each_with_index do |step_data, i|
    recipe.recipe_steps.create!(
      position: i + 1,
      title: step_data[:t],
      description: step_data[:d],
      estimated_minutes: step_data[:m]
    )
  end
end

